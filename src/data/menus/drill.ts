type Seg = [number, number, number, number];

/**
 * ローテーションの図。shots は、打つ順に番号を付ける。moves は、人の動き（回り方）で、番号は付けない。
 * 並んで待つ人は、コートの横に、数字（2, 3…）で置く。
 */
const flow = (players: DiagramPlayer[], shots: Seg[], moves: Seg[] = []): DrillDiagram => ({
  players,
  arrows: [
    ...shots.map(([a, b, c, d], i) => ({ ...shot(a, b, c, d), order: i + 1 })),
    ...moves.map(([a, b, c, d]) => move(a, b, c, d)),
  ],
});

