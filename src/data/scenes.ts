/**
 * 運動遊びなどの、上から見た場面図。人は色つきの丸のコマ。
 * ここは「初期の図」で、エディタ（/editor）で、メニューごとに自由に直せる。
 * 座標は幅320・高さ200。コートの線の範囲は、x 16〜304、y 22〜182。
 */

let seq = 0;
const nid = (p: string) => `${p}${(seq += 1)}`;

const T = (x: number, y: number, color: ColorName, label = "", o: { dir?: number; scale?: number } = {}): ScenePart => ({
  id: nid("t"),
  type: "token",
  x,
  y,
  color,
  ...(label ? { label } : {}),
  ...(o.dir !== undefined ? { dir: o.dir } : {}),
  ...(o.scale ? { scale: o.scale } : {}),
});
const Z = (x: number, y: number, w: number, h: number, color: ColorName, label = "", round = false): ScenePart => ({
  id: nid("z"),
  type: "zone",
  x,
  y,
  w,
  h,
  color,
  ...(label ? { label } : {}),
  ...(round ? { round: true } : {}),
});
const L = (x1: number, y1: number, x2: number, y2: number, color: ColorName = "red", o: { width?: number; dashed?: boolean } = {}): ScenePart => ({
  id: nid("l"),
  type: "line",
  x1,
  y1,
  x2,
  y2,
  color,
  width: o.width ?? 4,
  ...(o.dashed ? { dashed: true } : {}),
});
const A = (x1: number, y1: number, x2: number, y2: number, o: { bend?: number; dashed?: boolean; color?: ColorName } = {}): ScenePart => ({
  id: nid("a"),
  type: "arrow",
  x1,
  y1,
  x2,
  y2,
  color: o.color ?? "dark",
  ...(o.bend ? { bend: o.bend } : {}),
  ...(o.dashed ? { dashed: true } : {}),
});
const X = (x: number, y: number, text: string, o: { size?: number; color?: ColorName } = {}): ScenePart => ({ id: nid("x"), type: "text", x, y, text, size: o.size ?? 11, color: o.color ?? "dark" });
const B = (x: number, y: number, text: string, o: { size?: number } = {}): ScenePart => ({ id: nid("b"), type: "bubble", x, y, text, size: o.size ?? 11, color: "dark" });
const P = (kind: PropKind, x: number, y: number, o: { rot?: number; scale?: number; color?: ColorName } = {}): ScenePart => ({
  id: nid("p"),
  type: "prop",
  kind,
  x,
  y,
  ...(o.rot ? { rotation: o.rot } : {}),
  ...(o.scale ? { scale: o.scale } : {}),
  ...(o.color ? { color: o.color } : {}),
});

