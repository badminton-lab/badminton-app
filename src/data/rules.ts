function defineRules(category: RuleCategory, prefix: string) {
  let n = 0;
  return (
    question: string,
    answer: string,
    extra: { points?: string[]; basis?: string; note?: string } = {},
  ): Rule => ({
    id: `${prefix}${String(++n).padStart(2, "0")}`,
    category,
    question,
    answer,
    ...extra,
  });
}

